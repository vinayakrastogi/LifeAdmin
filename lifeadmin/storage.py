"""Small DB-API-style facade over SQLAlchemy for SQLite and PostgreSQL.

SQL values always remain bound parameters. Neither UI nor API caches connections;
both can point at the same Neon pooled connection string.
"""
from functools import lru_cache
import os

from sqlalchemy import create_engine, event, inspect, text
from sqlalchemy.engine import make_url
from sqlalchemy.exc import IntegrityError
from sqlalchemy.pool import NullPool


def database_url(local_path) -> str:
    configured = os.environ.get("LIFEADMIN_DATABASE_URL", "").strip()
    if not configured:
        return "sqlite:///" + str(local_path.resolve())
    try:
        url = make_url(configured)
        if url.drivername not in {"postgres", "postgresql", "postgresql+psycopg2"}:
            raise ValueError
        return url.set(drivername="postgresql+psycopg2").render_as_string(hide_password=False)
    except Exception:
        raise ValueError("LIFEADMIN_DATABASE_URL must be a PostgreSQL connection URL.") from None


@lru_cache(maxsize=8)
def _engine(url):
    sqlite = url.startswith("sqlite:")
    engine = create_engine(
        url, poolclass=NullPool, hide_parameters=True,
        connect_args={"timeout": 30} if sqlite else {"connect_timeout": 10},
    )
    if sqlite:
        @event.listens_for(engine, "connect")
        def configure(connection, _):
            # Explicit transactions make DDL + migrations atomic too.
            connection.isolation_level = None
            connection.execute("PRAGMA foreign_keys = ON")

        @event.listens_for(engine, "begin")
        def begin(connection):
            # Serialize SQLite writers/startup migrations across API and UI.
            connection.exec_driver_sql("BEGIN IMMEDIATE")
    return engine


class Row:
    """Preserve SQLite Row's named and positional access for existing callers."""
    def __init__(self, row):
        self._row = row

    def __getitem__(self, key):
        return self._row[key] if isinstance(key, int) else self._row._mapping[key]

    def keys(self):
        return self._row._mapping.keys()

    def __iter__(self):
        return iter(self._row)


class Result:
    def __init__(self, result):
        self._result = result
        self.rowcount = result.rowcount

    def fetchone(self):
        row = self._result.fetchone()
        return Row(row) if row is not None else None

    def fetchall(self):
        return [Row(row) for row in self._result.fetchall()]

    def __iter__(self):
        return (Row(row) for row in self._result)


class Connection:
    def __init__(self, url):
        self._connection = _engine(url).connect()
        self.postgres = self._connection.dialect.name == "postgresql"

    def execute(self, sql, values=()):
        # Application queries use qmarks; SQLAlchemy adapts named binds to each driver.
        parts = sql.split("?")
        if len(parts) - 1 != len(values):
            raise ValueError("SQL parameter count mismatch")
        statement = parts[0] + "".join(f":p{i}" + part for i, part in enumerate(parts[1:]))
        return Result(self._connection.execute(text(statement), {f"p{i}": v for i, v in enumerate(values)}))

    def executescript(self, script):
        if self.postgres:
            script = script.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                                    "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def columns(self, table):
        return {column["name"] for column in inspect(self._connection).get_columns(table)}

    def lock(self, name):
        if self.postgres:
            # Stable transaction-scoped locks, shared by independent UI/API processes.
            self.execute("SELECT pg_advisory_xact_lock(731902, ?)", (1 if name == "schema" else 2,))

    def close(self):
        self._connection.close()

    def __enter__(self):
        return self

    def __exit__(self, kind, error, traceback):
        if kind is None:
            self._connection.commit()
        else:
            self._connection.rollback()
